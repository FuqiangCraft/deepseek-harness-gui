/**
 * @fileoverview 第三方依赖许可证清单生成与校验工具
 * @description 扫描已安装 npm/pnpm 与 Cargo 依赖，拒绝未知或禁用许可证，并生成随安装包分发的统一声明。
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "THIRD_PARTY_LICENSES.txt");
const checkOnly = process.argv.includes("--check");
const forbidden = /(?:^|[ (])(?:AGPL|GPL|SSPL|BUSL|Commons-Clause)(?:[- )]|$)/i;

/** 读取 JSON 文件，失败时返回 null。 */
function readJson(file) {
  try { return JSON.parse(fs.readFileSync(file, "utf8")); } catch { return null; }
}

/** 规范化许可证字段。 */
function normalizeLicense(value) {
  if (typeof value === "string") return value.trim();
  if (value && typeof value.type === "string") return value.type.trim();
  if (Array.isArray(value)) return value.map(normalizeLicense).filter(Boolean).join(" OR ");
  return "UNKNOWN";
}

/** 返回依赖目录中的许可证正文文件。 */
function licenseFiles(dir) {
  try {
    return fs.readdirSync(dir).filter((name) => /^(?:licen[cs]e|copying|notice)(?:[._-].*)?$/i.test(name))
      .map((name) => path.join(dir, name)).filter((file) => fs.statSync(file).isFile());
  } catch { return []; }
}

/** 登记许可证正文并去重。 */
/** 登记许可证正文并去重。 */
function collectTexts(dir, texts) {
  for (const file of licenseFiles(dir)) {
    const content = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n").trim();
    if (content) texts.set(crypto.createHash("sha256").update(content).digest("hex"), content);
  }
}

/** 扫描 node_modules 中所有实际安装的包。 */
function scanNodeModules(nodeModules, records, texts, visited = new Set()) {
  if (!fs.existsSync(nodeModules)) return;
  let real;
  try { real = fs.realpathSync(nodeModules); } catch { return; }
  if (visited.has(real)) return;
  visited.add(real);
  for (const entry of fs.readdirSync(nodeModules, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === ".bin" || entry.name === ".pnpm") continue;
    const entryDir = path.join(nodeModules, entry.name);
    const dirs = entry.name.startsWith("@")
      ? fs.readdirSync(entryDir, { withFileTypes: true }).filter((item) => item.isDirectory()).map((item) => path.join(entryDir, item.name))
      : [entryDir];
    for (const dir of dirs) {
      const manifest = readJson(path.join(dir, "package.json"));
      if (!manifest?.name || !manifest?.version) continue;
      const license = normalizeLicense(manifest.license ?? manifest.licenses);
      records.set(`npm:${manifest.name}@${manifest.version}`, { ecosystem: "npm", name: manifest.name, version: manifest.version, license });
      collectTexts(dir, texts);
      scanNodeModules(path.join(dir, "node_modules"), records, texts, visited);
    }
  }
}

/** 使用 cargo metadata 扫描 Rust 依赖。 */
function scanCargo(records, texts) {
  try {
    execFileSync("cargo", ["fetch", "--manifest-path", path.join(root, "src-tauri", "Cargo.toml")], { stdio: "ignore" });
  } catch {}
  const raw = execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--manifest-path", path.join(root, "src-tauri", "Cargo.toml")], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  for (const pkg of JSON.parse(raw).packages) {
    if (pkg.name === "harness-desktop") continue;
    records.set(`cargo:${pkg.name}@${pkg.version}`, { ecosystem: "cargo", name: pkg.name, version: pkg.version, license: normalizeLicense(pkg.license) });
    collectTexts(path.dirname(pkg.manifest_path), texts);
  }
}

const records = new Map();
const texts = new Map();
scanNodeModules(path.join(root, "node_modules"), records, texts);
scanNodeModules(path.join(root, "sidecar", "node_modules"), records, texts);
scanCargo(records, texts);
const packages = [...records.values()].sort((a, b) => `${a.ecosystem}:${a.name}@${a.version}`.localeCompare(`${b.ecosystem}:${b.name}@${b.version}`));
const invalid = packages.filter((pkg) => pkg.license === "UNKNOWN" || forbidden.test(pkg.license));
if (invalid.length) throw new Error(`许可证门禁失败:\n${invalid.map((pkg) => `${pkg.ecosystem}:${pkg.name}@${pkg.version} ${pkg.license}`).join("\n")}`);

const lines = ["THIRD-PARTY SOFTWARE NOTICES", "Generated by scripts/generate-third-party-licenses.js. Do not edit manually.", "", "PACKAGE INVENTORY",
  ...packages.map((pkg) => `${pkg.ecosystem}\t${pkg.name}\t${pkg.version}\t${pkg.license}`), "", "LICENSE TEXTS"];
for (const [hash, content] of [...texts.entries()].sort(([a], [b]) => a.localeCompare(b))) lines.push("", `----- SHA256 ${hash} -----`, content);
const generated = `${lines.join("\n")}\n`;
if (checkOnly) {
  if (!fs.existsSync(outputPath) || fs.statSync(outputPath).size === 0) {
    throw new Error("THIRD_PARTY_LICENSES.txt 不存在或为空，请运行 npm run licenses:generate");
  }
  console.log(`[licenses] verified ${packages.length} packages and ${texts.size} unique license texts against compliance policy`);
} else {
  fs.writeFileSync(outputPath, generated, "utf8");
  console.log(`[licenses] wrote ${outputPath}: ${packages.length} packages, ${texts.size} unique license texts`);
}
